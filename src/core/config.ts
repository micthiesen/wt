/**
 * Trigger vocabulary for `[[automations]]`. Each is a LEVEL condition
 * evaluated against the aggregated row state (see
 * `tui/automation-rules.ts` for the exact predicate + fire-key shape):
 *
 *   "pr.checks.failed"        — open PR's checks rollup is failing.
 *   "review_bot.unresolved"   — the configured review bot has
 *                               unresolved findings (threads or
 *                               checklist items, per `[review_bot]`).
 *                               "rabbit.unresolved" is accepted as a
 *                               legacy alias in config files.
 *   "review.changes_requested"— a human review requested changes.
 *   "pr.conflict"             — merge-tree probe says the branch
 *                               conflicts with its effective base.
 *   "wt.merged"               — a NON-stacked worktree's branch landed
 *                               (merged / gone / PR merged — same set
 *                               the `c` clean sweep uses). Exception:
 *                               rules running `builtin:close-issue`
 *                               also evaluate stack members — that run
 *                               never touches the worktree, so the
 *                               clean-vs-restack race the exclusion
 *                               protects against doesn't apply.
 *   "stack.parent_merged"     — a stack (worktrees chained by their
 *                               recorded fork bases) has a merged
 *                               member with open members stacked on it.
 */
export type AutomationTrigger =
  | "pr.checks.failed"
  | "review_bot.unresolved"
  | "review.changes_requested"
  | "pr.conflict"
  | "wt.merged"
  | "wt.created"
  | "stack.parent_merged"
  // Work-status assertions (`wt status`; see core/work-status.ts). Level
  // conditions like everything else; the fire key carries the assertion
  // timestamp, so re-asserting the same state re-fires.
  | "status.needs_human"
  | "status.needs_testing"
  | "status.ready"
  /**
   * A branch has LANDED still owing a deployed-environment check
   * (`wt status --verify-after-merge`) and has owed it for longer than
   * `after_days`. The one trigger here that fires REPEATEDLY: its fire
   * key carries the local day, so it re-fires once a day until someone
   * asserts `verified`.
   *
   * That is deliberate and is the opposite of the echo problem the
   * `by`-stamp exists for. A daily reminder is only noise when the
   * recipient can clear it by writing something; this one clears only
   * by the check actually happening, and the failure it exists to
   * catch — a post-merge verification nobody runs — is silent by
   * construction, because the row otherwise reads as merged and done.
   */
  | "status.verification_overdue"
  /**
   * A watched branch's tip MOVED. Fleet-level: it targets no worktree,
   * because by the time it fires the worktrees whose work is in that
   * range are long gone — which is exactly why it exists. The run is
   * launched in the main clone with `{{branch}}`, `{{from}}` and
   * `{{to}}`, and the range walk is the run's job.
   *
   * `from` comes from a watermark wt advances on dispatch. The FIRST
   * observation of a branch records the sha and fires nothing: there is
   * no range yet, and treating an absent watermark as "the beginning of
   * history" would fire once for every commit ever made. Absence means
   * unknown, never fire-for-everything.
   */
  | "branch.advanced";

/**
 * What to do when the target worktree isn't quiescent at delivery time
 * (live session working/asking, action running, recent edits):
 * `queue` (default) holds the intent and delivers once things settle;
 * `skip` marks the fire handled and does nothing. There is deliberately
 * no "force" so delivery does not collide with an `asking` session.
 */
export type AutomationBusyPolicy = "queue" | "skip";

/** `run` targets that dispatch built-in flows instead of an [[actions]] def. */
export const AUTOMATION_BUILTINS = [
  "builtin:restack",
  "builtin:clean",
  "builtin:notify",
  "builtin:close-issue",
  "builtin:delete-branch",
] as const;
export type AutomationBuiltin = (typeof AUTOMATION_BUILTINS)[number];

/**
 * One `[[automations]]` binding: when `on` holds for a worktree (and
 * the fire key is unseen), run `run` — an `[[actions]]` id (inheriting
 * its target/affects/requires) or a `builtin:` flow. No defaults ship;
 * an absent section means nothing is automated.
 */
export type AutomationDef = {
  id: string;
  on: AutomationTrigger;
  /** An [[actions]] id, or one of AUTOMATION_BUILTINS. */
  run: string;
  busy: AutomationBusyPolicy;
  /** Minimum minutes between dispatches per (rule, worktree). Null = none. */
  cooldownMinutes: number | null;
  /**
   * `status.verification_overdue` only: how long an outstanding
   * post-merge verification may sit before it starts firing. A knob
   * because deploy cadence is the one thing wt cannot guess — a fleet
   * that deploys on merge wants 1, one that batches a weekly release
   * wants 7, and a default that is wrong in either direction turns the
   * reminder into noise or into nothing. Ignored by every other
   * trigger.
   */
  afterDays: number;
  /**
   * Quiescence window: the intent must be at least this old AND the
   * worktree free of edits for this long before delivery. Doubles as
   * the human-cancellation grace period. Defaults per trigger: merge
   * triggers (`wt.merged`, `stack.parent_merged`) can't flap — a merge
   * doesn't un-happen — so they default short; the rest default long
   * enough to ride out CI/review churn.
   */
  settleSeconds: number;
  /**
   * `branch.advanced` only: which branch to watch. Required there and
   * rejected everywhere else — a trigger whose subject is a branch has
   * no sensible default, and guessing the trunk would silently watch
   * the wrong thing on the fleets this exists for (two-tier trunks,
   * where the release branch is precisely NOT the one you fork from).
   */
  branch: string | null;
};


function configPath(): { path: string; present: boolean } {
  const explicit = process.env.WT_CONFIG;
  if (explicit) {
    const p = expandHome(explicit);
    return { path: p, present: existsSync(p) };
  }
  const xdg = process.env.XDG_CONFIG_HOME;
  const dir = xdg ? expandHome(xdg) : join(HOME, ".config");
  const p = join(dir, "wt", "config.toml");
  return { path: p, present: existsSync(p) };
}

type Raw = RawConfig;

function obj(v: unknown): Raw | null {
  return v && typeof v === "object" && !Array.isArray(v) ? (v as Raw) : null;
}

/**
 * A TOML value that may be one string or a list of them. `summary_marker`
 * shipped as a bare string and grew a second entry when the review bot
 * started posting delta findings under their own heading; widening in
 * place is what keeps a config that loaded yesterday loading today.
 */
function strOrStrArr(v: unknown): readonly string[] {
  if (typeof v === "string") return v ? [v] : [];
  if (Array.isArray(v)) return v.filter((x): x is string => typeof x === "string" && x !== "");
  return [];
}

function strArr(v: unknown, fallback: readonly string[]): readonly string[] {
  if (!Array.isArray(v)) return fallback;
  const out: string[] = [];
  for (const x of v) if (typeof x === "string") out.push(x);
  return out;
}

function unsafeCopyGlob(pattern: string): boolean {
  return isAbsolute(pattern) ||
    /^[a-zA-Z]:[\\/]/.test(pattern) ||
    pattern.split(/[\\/]+/).includes("..");
}

class Errors {
  private list: string[] = [];
  add(msg: string) {
    this.list.push(msg);
  }
  /** Read a required string field; record an error and return "" on miss. */
  reqStr(parent: Raw | null, section: string, key: string): string {
    const v = parent?.[key];
    if (typeof v === "string" && v.length > 0) return v;
    this.add(`${section}.${key} is required`);
    return "";
  }
  optStr(parent: Raw | null, key: string, fallback: string): string {
    const v = parent?.[key];
    return typeof v === "string" && v.length > 0 ? v : fallback;
  }
  optStrOrNull(parent: Raw | null, key: string): string | null {
    const v = parent?.[key];
    return typeof v === "string" && v.length > 0 ? v : null;
  }
  optNum(parent: Raw | null, key: string, fallback: number): number {
    const v = parent?.[key];
    return typeof v === "number" && Number.isFinite(v) ? v : fallback;
  }
  /**
   * Optional number with no default. Null means "unset", which for
   * `dev_server.max_concurrent` means "no cap" — distinct from any
   * number the key could carry, so it can't be folded into `optNum`
   * with a sentinel fallback.
   */
  optNumOrNull(parent: Raw | null, key: string): number | null {
    const v = parent?.[key];
    return typeof v === "number" && Number.isFinite(v) ? v : null;
  }
  /** Read an optional string-enum field; record an error on a value outside `allowed`. */
  optEnum<T extends string>(
    parent: Raw | null,
    section: string,
    key: string,
    allowed: readonly T[],
    fallback: T,
  ): T {
    const v = parent?.[key];
    if (v === undefined) return fallback;
    if (typeof v === "string" && (allowed as readonly string[]).includes(v)) {
      return v as T;
    }
    this.add(`${section}.${key} must be one of: ${allowed.join(", ")}`);
    return fallback;
  }
  /** True when any recorded error message starts with `prefix`. */
  has(prefix: string): boolean {
    return this.list.some((l) => l.startsWith(prefix));
  }
  flush(configFile: string, hints: readonly string[] = []): void {
    if (this.list.length === 0) return;
    const lines = this.list.map((l) => `  - ${l}`).join("\n");
    const hintLines = hints.length > 0
      ? `\n${hints.map((h) => `hint: ${h}`).join("\n")}\n`
      : "";
    process.stderr.write(
      `wt: invalid config at ${configFile}\n${lines}\n${hintLines}` +
        `\nSee src/core/config.ts for the full schema.\n`,
    );
    process.exit(1);
  }
}

function loadRaw(path: string, present: boolean, errs: Errors): Raw {
  if (!present) {
    errs.add(`config file not found at ${path}`);
    return {};
  }
  try {
    const text = readFileSync(path, "utf8");
    const parsed = Bun.TOML.parse(text);
    return obj(parsed) ?? {};
  } catch (err) {
    errs.add(`failed to parse ${path}: ${(err as Error).message}`);
    return {};
  }
}

function build(
  raw: Raw,
  errs: Errors,
  repositoryConfig: string | null = null,
): Config {
  const instance = obj(raw.instance);
  const harnessRaw = obj(raw.harness);
  const paths = obj(raw.paths);
  const branch = obj(raw.branch);
  const stage = obj(raw.stage);
  const lifecycle = obj(raw.lifecycle);
  const deploy = obj(raw.deploy);
  const sstRaw = deploy ? obj(deploy.sst) : null;
  const tracker = obj(raw.issue_tracker);
  const linearRaw = tracker ? obj(tracker.linear) : null;
  const remoteRaw = obj(raw.remote);
  const ui = obj(raw.ui);

  const instanceRole = errs.optEnum(
    instance,
    "instance",
    "role",
    ["controller", "worker"] as const,
    "controller",
  );
  const primaryHarness = errs.optEnum(
    harnessRaw,
    "harness",
    "primary",
    HARNESS_IDS,
    GENERIC_DEFAULTS.harness.primary,
  );
  const hiddenHarnesses = new Set<HarnessId>();
  const hiddenRaw = harnessRaw?.hidden;
  let hiddenIds: readonly unknown[] = GENERIC_DEFAULTS.harness.hidden;
  if (hiddenRaw !== undefined) {
    if (Array.isArray(hiddenRaw)) {
      hiddenIds = hiddenRaw;
    } else {
      errs.add("harness.hidden must be an array of strings");
      hiddenIds = [];
    }
  }
  for (const id of hiddenIds) {
    if (typeof id !== "string") {
      errs.add("harness.hidden entries must be strings");
      continue;
    }
    if ((HARNESS_IDS as readonly string[]).includes(id)) {
      hiddenHarnesses.add(id as HarnessId);
    } else {
      errs.add(
        `harness.hidden: unknown harness "${id}" (expected one of ${HARNESS_IDS.join(", ")})`,
      );
    }
  }
  if (hiddenHarnesses.size === HARNESS_IDS.length) {
    errs.add("harness.hidden cannot hide every harness");
  }
  if (hiddenHarnesses.has(primaryHarness)) {
    errs.add(`harness.primary "${primaryHarness}" cannot also appear in harness.hidden`);
  }

  const branchPrefix = errs.reqStr(branch, "branch", "prefix");
  const branchBase = errs.optStr(branch, "base", GENERIC_DEFAULTS.branch.base);
  const idPattern = errs.optStr(branch, "id_pattern", GENERIC_DEFAULTS.branch.idPattern);
  // Compile-validate at load time — stage.ts does `new RegExp(idPattern,
  // "i")` at module init with no try/catch, so a bad pattern would
  // otherwise throw an uncaught SyntaxError on startup instead of
  // failing the config loader with a normal error.
  try {
    new RegExp(idPattern);
  } catch (err) {
    errs.add(`branch.id_pattern: invalid regex (${(err as Error).message})`);
  }
  const slugMaxLen = errs.optNum(branch, "slug_max_len", GENERIC_DEFAULTS.branch.slugMaxLen);
  // Blank entries dropped rather than rejected: the cost of a stray ""
  // in a list is a git call that fails on every fetch, and the value of
  // failing the whole load over one is nil.
  const keepFresh = strArr(branch?.keep_fresh, []).filter((b) => b.trim() !== "");

  const mainClone = expandHome(errs.reqStr(paths, "paths", "main_clone"));
  const worktreeRoot = expandHome(errs.reqStr(paths, "paths", "worktree_root"));
  const repositoryConfigDir = repositoryConfig
    ? dirname(
      existsSync(repositoryConfig) ? realpathSync(repositoryConfig) : resolve(repositoryConfig),
    )
    : null;
  // A worktree carries a COPY of the repository's `.wt.toml` — the backends
  // clone the whole tree — so a config found under `worktree_root` identifies
  // a WORKTREE, never a repository. Deriving identity from the config's own
  // directory therefore gave every worktree its own `repoId`, which
  // partitioned durable state per worktree instead of per repository: a work
  // status asserted in one worktree was invisible from every other, and
  // `wt status --all` / `wt fleet` / `wt ls --json` answered differently
  // depending on which worktree you ran them from, each seeing only its own
  // row while every other read as "no status asserted". Same split in the
  // other direction for records written from the main clone (a `--gh` issue
  // attached at `wt new` was invisible from inside the worktree it named).
  //
  // The repository IS the main clone — that is what `paths.main_clone` names
  // and what every worktree of it shares — so identity comes from there
  // whenever the nearest config turns out to be a worktree's copy. A
  // `.wt.toml` outside `worktree_root` is still a repository root and still
  // names itself, which keeps multi-repo isolation intact.
  const configIsWorktreeCopy = repositoryConfigDir !== null &&
    isInsidePath(worktreeRoot, repositoryConfigDir);
  const identifyByMainClone = repositoryConfig === null || configIsWorktreeCopy;
  const repoPath = identifyByMainClone
    ? (existsSync(mainClone) ? realpathSync(mainClone) : mainClone)
    : repositoryConfigDir!;
  const repoId = identifyByMainClone
    ? pathNamespace(mainClone, HOME)
    : repositoryNamespace(repositoryConfig!, HOME);
  // Partitioned layout when the REPOSITORY declares itself with its own
  // `.wt.toml`; the shared compatibility layout otherwise. Keyed on the same
  // fact `repoId` is, and deliberately not on "did discovery find a file":
  // discovery finds a worktree's copy from inside that worktree and nothing at
  // all from a shell outside the repo, so that predicate answered differently
  // for one repository depending on where the command ran — and every path
  // below it followed, giving one board two state databases, two cache roots
  // and two tmux servers that could not see each other.
  const ownRepositoryConfig = !identifyByMainClone;
  const defaultCacheDb = ownRepositoryConfig
    ? join(HOME, ".cache", "wt", repoId, "cache.sqlite")
    : GENERIC_DEFAULTS.paths.cacheDb;
  const cacheDb = expandHome(errs.optStr(paths, "cache_db", defaultCacheDb));
  const defaultStateDb = ownRepositoryConfig
    ? join(HOME, ".local", "state", "wt", "wt.sqlite")
    : join(dirname(cacheDb), "wt.sqlite");
  const stateDb = expandHome(errs.optStr(paths, "state_db", defaultStateDb));
  // Disposable/runtime files anchor here; durable board state is in stateDb.
  // log_dir/lock_dir remain relative so relocating cache_db moves that runtime.
  const cacheRoot = dirname(cacheDb);
  const logDir = expandHome(errs.optStr(paths, "log_dir", join(cacheRoot, "logs")));
  // Sibling subdir for structured app logs — keeps daily `wt-*.log`
  // files separate from the per-worktree `<slug>-*.log` destroy logs
  // that `wt logs <slug>` reads. Not user-configurable; fold into
  // `log_dir` if the user moved that.
  const appLogDir = join(logDir, "app");
  const lockDir = expandHome(errs.optStr(paths, "lock_dir", join(cacheRoot, "locks")));
  const weztermCliRaw =
    errs.optStrOrNull(paths, "wezterm_cli") ?? GENERIC_DEFAULTS.paths.weztermCli;
  const weztermCli = weztermCliRaw ? expandHome(weztermCliRaw) : null;
  const dotfiles = expandHome(
    errs.optStr(paths, "dotfiles", GENERIC_DEFAULTS.paths.dotfiles),
  );

  // Stage prefix derives from branch.prefix when omitted — the
  // overwhelmingly common shape is `<branch.prefix>-<stage>`. Same
  // for the personal stage name, which is just the bare prefix.
  const stagePrefix = errs.optStr(stage, "prefix", `${branchPrefix}-`);
  const stageDefault = errs.optStr(stage, "default_personal", branchPrefix);
  const stageDomain = errs.optStrOrNull(stage, "domain");

  const envFiles = strArr(lifecycle?.env_files_to_copy, GENERIC_DEFAULTS.lifecycle.envFilesToCopy);
  const copyGlobs = strArr(lifecycle?.copy_globs, GENERIC_DEFAULTS.lifecycle.copyGlobs);
  if (copyGlobs.some(unsafeCopyGlob)) {
    errs.add("lifecycle.copy_globs entries must be relative paths without '..' segments");
  }
  const installCommand = errs.optStrOrNull(lifecycle, "install_command");
  const destroyCommand = errs.optStrOrNull(lifecycle, "destroy_command");

  // Worktree backend — opt-in. Absent section (or absent key) means the
  // default `git-worktree`; `rift` switches new creates to CoW clones.
  const backendRaw = obj(raw.backend);
  const backendKind = errs.optEnum(
    backendRaw,
    "backend",
    "kind",
    ["git-worktree", "rift"] as const satisfies readonly BackendKind[],
    "git-worktree",
  );

  // SST and Linear are entirely optional — absence of the section
  // disables the integration. When the section IS present, every
  // required field within it must be set.
  const sst: SstConfig | null = sstRaw === null
    ? null
    : {
      stateBucket: errs.reqStr(sstRaw, "deploy.sst", "state_bucket"),
      statePrefix: errs.reqStr(sstRaw, "deploy.sst", "state_prefix"),
      awsProfile: errs.reqStr(sstRaw, "deploy.sst", "aws_profile"),
      autoRegenPaths: strArr(sstRaw.auto_regen_paths, GENERIC_DEFAULTS.sst.autoRegenPaths),
    };

  // [issue_tracker] presence alone enables the issue row (bare parsed
  // id); an explicit url_template — or the [issue_tracker.linear]
  // preset, which derives one from the workspace — upgrades it to a
  // deep link. An explicit template wins over the preset.
  let issueTracker: IssueTrackerConfig | null = null;
  if (tracker !== null) {
    const explicitTemplate = errs.optStrOrNull(tracker, "url_template");
    if (explicitTemplate && !explicitTemplate.includes("{id}")) {
      errs.add("issue_tracker.url_template must contain the {id} placeholder");
    }
    let urlTemplate = explicitTemplate;
    if (!urlTemplate && linearRaw !== null) {
      const workspace = errs.reqStr(linearRaw, "issue_tracker.linear", "workspace");
      // linear:// deep-link scheme — opens the desktop app directly.
      urlTemplate = `linear://${workspace}/issue/{id}`;
    }
    const prefix = errs.optStrOrNull(tracker, "prefix");
    if (prefix && !/^[a-z]+$/.test(prefix)) {
      errs.add("issue_tracker.prefix must be lowercase letters (e.g. \"coz\")");
    }
    const rawReader = tracker.read_command;
    let readCommand: string[] | null = null;
    if (rawReader !== undefined) {
      if (!Array.isArray(rawReader) || rawReader.some((arg) => typeof arg !== "string" || !arg.trim() || arg.includes("\0"))) {
        errs.add("issue_tracker.read_command must be an array of nonempty strings (argv, not a shell command)");
      } else if (rawReader.length > 0) {
        if (rawReader[0].includes("{id}") || !rawReader.slice(1).some((arg: string) => arg.includes("{id}"))) {
          errs.add("issue_tracker.read_command must contain {id} in an argument, not the executable");
        }
        readCommand = [expandHome(rawReader[0]), ...rawReader.slice(1)];
      }
    }
    const rawStatus = tracker.status_command;
    let statusCommand: string[] | null = null;
    if (rawStatus !== undefined) {
      if (!Array.isArray(rawStatus) || rawStatus.some((arg) => typeof arg !== "string" || !arg.trim() || arg.includes("\0"))) {
        errs.add("issue_tracker.status_command must be an array of nonempty strings (argv, not a shell command)");
      } else if (rawStatus.length > 0) {
        if (rawStatus[0].includes("{ids}") || rawStatus.filter((arg) => arg === "{ids}").length !== 1 || rawStatus.some((arg) => arg.includes("{ids}") && arg !== "{ids}")) {
          errs.add("issue_tracker.status_command must contain exactly one standalone {ids} argument, not the executable");
        }
        statusCommand = [expandHome(rawStatus[0]), ...rawStatus.slice(1)];
      }
    }
    const statusStyles: Record<string, IssueStatusStyle> = {};
    if (tracker.status_styles !== undefined) {
      const styles = obj(tracker.status_styles);
      if (!styles) errs.add("issue_tracker.status_styles must be a table of status labels to { icon, color }");
      else for (const [label, rawStyle] of Object.entries(styles)) {
        const style = obj(rawStyle);
        const icon = ISSUE_STATUS_ICONS.find((candidate) => candidate === style?.icon);
        if (!label.trim() || /[\x00-\x1f\x7f]/.test(label) || !style ||
          !icon || typeof style.color !== "string" ||
          !/^#[0-9a-fA-F]{6}$/.test(style.color) || Object.keys(style).some((key) => key !== "icon" && key !== "color")) {
          errs.add(`issue_tracker.status_styles.${label} needs icon (${ISSUE_STATUS_ICONS.join("|")}) and color (#RRGGBB)`);
        } else statusStyles[label] = { icon, color: style.color };
      }
    }
    issueTracker = { urlTemplate, prefix: prefix || null, readCommand, statusCommand, statusStyles };
  }

  // [review_bot] — absent means the CodeRabbit preset, preserving the
  // previously-hardcoded default behavior. Checklist mode has no sane
  // CodeRabbit-shaped fallbacks: the login and summary marker identify a
  // *different* bot, so both must be explicit, and the check-context
  // default flips to "none" rather than inheriting CodeRabbit's.
  const reviewBotRaw = obj(raw.review_bot);
  const reviewBotVia = errs.optEnum(
    reviewBotRaw,
    "review_bot",
    "unresolved_via",
    ["threads", "checklist"] as const satisfies readonly ReviewBotUnresolvedVia[],
    GENERIC_DEFAULTS.reviewBot.unresolvedVia,
  );
  const isChecklist = reviewBotVia === "checklist";
  const reviewBot: ReviewBotConfig = {
    name: errs.optStr(reviewBotRaw, "name", GENERIC_DEFAULTS.reviewBot.name),
    login: (isChecklist
      ? errs.reqStr(reviewBotRaw, "review_bot", "login")
      : errs.optStr(reviewBotRaw, "login", GENERIC_DEFAULTS.reviewBot.login)
    ).replace(/\[bot\]$/, ""),
    checkContexts: strArr(
      reviewBotRaw?.check_contexts,
      isChecklist ? [] : GENERIC_DEFAULTS.reviewBot.checkContexts,
    ),
    unresolvedVia: reviewBotVia,
    summaryMarkers: strOrStrArr(reviewBotRaw?.summary_marker),
    pendingMarker: errs.optStrOrNull(reviewBotRaw, "pending_marker"),
    rerunCommand: errs.optStrOrNull(reviewBotRaw, "rerun_command"),
  };
  if (isChecklist && reviewBot.summaryMarkers.length === 0) {
    errs.add('review_bot.summary_marker is required when unresolved_via = "checklist"');
  }

  // [dev_server] — optional; presence turns on the per-worktree dev
  // server (row, bolt, `!` picker builtins, `wt dev`).
  const devServerRaw = obj(raw.dev_server);
  let devServer: DevServerConfig | null = null;
  if (devServerRaw !== null) {
    const portBase = errs.optNum(devServerRaw, "port_base", 8100);
    const portRange = errs.optNum(devServerRaw, "port_range", 100);
    if (!Number.isInteger(portBase) || portBase < 1 || portBase > 65_535) {
      errs.add("dev_server.port_base must be a port number (1-65535)");
    }
    if (!Number.isInteger(portRange) || portRange < 1 || portBase + portRange > 65_536) {
      errs.add("dev_server.port_range must keep the range within 1-65535");
    }
    const maxConcurrent = errs.optNumOrNull(devServerRaw, "max_concurrent");
    if (maxConcurrent !== null && (!Number.isInteger(maxConcurrent) || maxConcurrent < 1)) {
      errs.add("dev_server.max_concurrent must be a positive integer (omit it for no cap)");
    }
    devServer = {
      command: errs.reqStr(devServerRaw, "dev_server", "command"),
      portBase,
      portRange,
      urlTemplate: errs.optStr(devServerRaw, "url", "http://localhost:{{port}}/"),
      maxConcurrent,
      stopCommand: errs.optStrOrNull(devServerRaw, "stop_command"),
      resetCommand: errs.optStrOrNull(devServerRaw, "reset_command"),
      healthCommand: errs.optStrOrNull(devServerRaw, "health_command"),
    };
  }

  const remoteHost = remoteRaw === null
    ? ""
    : errs.reqStr(remoteRaw, "remote", "host");
  const remote: RemoteConfig | null = remoteRaw === null
    ? null
    : {
      host: remoteHost,
      label: errs.optStr(remoteRaw, "label", remoteHost),
      wtPath: errs.optStr(remoteRaw, "wt_path", "~/.wt/bin/wt"),
    };

  const namingRaw = obj(raw.naming);
  const namingModelsRaw = namingRaw ? obj(namingRaw.models) : null;
  const namingClaudeModel = errs.optStrOrNull(namingModelsRaw, "claude");
  const namingCodexModel = errs.optStrOrNull(namingModelsRaw, "codex");
  const namingOpencodeModel = errs.optStrOrNull(namingModelsRaw, "opencode");
  if (obj(raw.ai) !== null) {
    errs.add("[ai] is no longer supported; use [naming] with a coding-agent harness");
  }
  const naming: NamingConfig | null = namingRaw === null
    ? null
    : {
      harness: errs.optEnum(
        namingRaw,
        "naming",
        "harness",
        ["primary", "claude", "codex", "opencode"] as const,
        GENERIC_DEFAULTS.naming.harness,
      ),
      models: {
        ...(namingClaudeModel ? { claude: namingClaudeModel } : {}),
        ...(namingCodexModel ? { codex: namingCodexModel } : {}),
        ...(namingOpencodeModel ? { opencode: namingOpencodeModel } : {}),
      },
      reasoningEffort: errs.optEnum(
        namingRaw,
        "naming",
        "reasoning_effort",
        ["minimal", "low", "medium", "high", "xhigh", "max"] as const,
        GENERIC_DEFAULTS.naming.reasoningEffort,
      ),
      maxInputTokens: errs.optNum(
        namingRaw,
        "max_input_tokens",
        GENERIC_DEFAULTS.naming.maxInputTokens,
      ),
      timeoutMs: errs.optNum(
        namingRaw,
        "timeout_ms",
        GENERIC_DEFAULTS.naming.timeoutMs,
      ),
    };

  const diffRaw = obj(raw.diff);
  const diff: DiffConfig = {
    command: errs.optStr(diffRaw, "command", GENERIC_DEFAULTS.diff.command),
  };

  const editor: EditorConfig = {
    command: errs.optStrOrNull(obj(raw.editor), "command"),
  };

  const browser: BrowserConfig = {
    chromeProfile: errs.optStrOrNull(obj(raw.browser), "chrome_profile"),
  };

  // `WT_TMUX_SOCKET` wins: it is the knob that propagates into every
  // child process, so a session already spawned under it must keep
  // resolving the same server no matter what the config says.
  const tmuxSocket = process.env.WT_TMUX_SOCKET?.trim() ||
    errs.optStr(obj(raw.tmux), "socket", ownRepositoryConfig ? `wt-${repoId}` : "wt");
  const terminalConfig = obj(raw.tmux)?.terminal_config;
  if (terminalConfig !== undefined && typeof terminalConfig !== "string") {
    errs.add("tmux.terminal_config must be a string");
  }
  const codexRaw = obj(raw.codex);
  const animations = codexRaw?.animations;
  if (animations !== undefined && typeof animations !== "boolean") {
    errs.add("codex.animations must be a boolean");
  }
  const codex = {
    animations: typeof animations === "boolean" ? animations : false,
    alternateScreen: errs.optEnum(
      codexRaw, "codex", "alternate_screen", ["always", "auto", "never"] as const, "always",
    ),
  };

  const rows = strArr(ui?.rows, GENERIC_DEFAULTS.ui.rows);
  const hiddenBadges = new Set<BadgeSlot>();
  for (const id of strArr(ui?.hidden_badges, [])) {
    if ((BADGE_SLOTS as readonly string[]).includes(id)) {
      hiddenBadges.add(id as BadgeSlot);
    } else {
      errs.add(
        `ui.hidden_badges: unknown badge "${id}" (expected one of ${BADGE_SLOTS.join(", ")})`,
      );
    }
  }
  const uiSort = errs.optEnum(
    ui,
    "ui",
    "sort",
    ["status", "manual"] as const,
    "status",
  );
  const uiActivityPane = errs.optEnum(
    ui,
    "ui",
    "activity_pane",
    ["column", "full_width"] as const,
    "column",
  );

  const skillsRaw = obj(raw.skills);
  const startupCheckRaw = skillsRaw?.startup_check;
  if (startupCheckRaw !== undefined && typeof startupCheckRaw !== "boolean") {
    errs.add("skills.startup_check must be a boolean");
  }
  const skills = { startupCheck: startupCheckRaw !== false };

  const managerRaw = obj(raw.manager);
  const wtFeedbackRaw = managerRaw?.wt_feedback;
  if (wtFeedbackRaw !== undefined && typeof wtFeedbackRaw !== "boolean") {
    errs.add("manager.wt_feedback must be a boolean");
  }
  const manager = { wtFeedback: wtFeedbackRaw === true };

  const updateRaw = obj(raw.update);
  const updateStartupRaw = updateRaw?.startup_check;
  if (updateStartupRaw !== undefined && typeof updateStartupRaw !== "boolean") {
    errs.add("update.startup_check must be a boolean");
  }
  const update = { startupCheck: updateStartupRaw !== false };

  const githubRaw = obj(raw.github);
  const githubReviewersRaw = githubRaw?.reviewers;
  if (
    githubReviewersRaw !== undefined &&
    typeof githubReviewersRaw !== "boolean"
  ) {
    errs.add("github.reviewers must be a boolean");
  }
  const githubEventsRaw = githubRaw ? obj(githubRaw.events) : null;
  const githubEventsSecretFile = githubEventsRaw
    ? errs.optStrOrNull(githubEventsRaw, "secret_file")
    : null;
  let githubEvents: GithubEventsConfig | null = null;
  if (githubEventsRaw !== null) {
    const port = errs.optNum(githubEventsRaw, "port", 8765);
    if (!Number.isInteger(port) || port < 1 || port > 65_535) {
      errs.add("github.events.port must be a port number (1-65535)");
    }
    const backstopPollMs = errs.optNum(githubEventsRaw, "backstop_poll_ms", 600_000);
    if (!Number.isFinite(backstopPollMs) || backstopPollMs <= 0) {
      errs.add("github.events.backstop_poll_ms must be a positive number");
    }
    githubEvents = {
      port,
      host: errs.optStr(githubEventsRaw, "host", "127.0.0.1"),
      secret: errs.optStrOrNull(githubEventsRaw, "secret"),
      secretFile: githubEventsSecretFile ? expandHome(githubEventsSecretFile) : null,
      backstopPollMs,
    };
  }
  const github: GithubConfig = {
    reviewers: githubReviewersRaw !== false,
    ignoredReviewRepositories: strArr(githubRaw?.ignored_review_repositories, []),
    ignoredChecks: strArr(githubRaw?.ignored_checks, []),
    defaultReviewer: errs.optStrOrNull(githubRaw, "default_reviewer"),
    prTarget: errs.optEnum(
      githubRaw,
      "github",
      "pr_target",
      ["github", "linear"] as const satisfies readonly PullRequestTarget[],
      GENERIC_DEFAULTS.github.prTarget,
    ),
    events: githubEvents,
  };

  // [[actions]] is fully replaced when the user provides any entries
  // (even just one) — otherwise the built-in defaults apply. That way
  // a user can drop a default they don't want simply by listing the
  // ones they keep.
  const actions = parseActions(raw.actions, errs);
  // [[automations]] has NO defaults — automation is strictly opt-in.
  // Parsed after actions so `run` references validate against the
  // final action list.
  const automations = parseAutomations(raw.automations, actions, { base: branchBase, keepFresh }, errs);

  return {
    instance: { role: instanceRole },
    harness: { primary: primaryHarness, hidden: hiddenHarnesses },
    repoId,
    repoPath,
    paths: {
      mainClone,
      worktreeRoot,
      logDir,
      appLogDir,
      lockDir,
      cacheDb,
      stateDb,
      cacheRoot,
      weztermCli,
      dotfiles,
    },
    tmux: {
      socket: tmuxSocket,
      terminalConfig: typeof terminalConfig === "string" ? terminalConfig : null,
    },
    codex,
    branch: { prefix: branchPrefix, base: branchBase, idPattern, slugMaxLen, keepFresh },
    stage: { prefix: stagePrefix, defaultPersonal: stageDefault, domain: stageDomain },
    lifecycle: { envFilesToCopy: envFiles, copyGlobs, installCommand, destroyCommand },
    backend: { kind: backendKind },
    sst,
    issueTracker,
    reviewBot,
    devServer,
    remote,
    naming,
    diff,
    editor,
    browser,
    github,
    actions,
    automations,
    ui: { rows, hiddenBadges, sort: uiSort, activityPane: uiActivityPane,
      hideTerminalApps: strArr(ui?.hide_terminal_apps, []),
      actionGroupsLast: strArr(ui?.action_groups_last, []),
    },
    skills,
    manager,
    update,
  };
}

const VALID_TRIGGERS = new Set<AutomationTrigger>([
  "pr.checks.failed",
  "review_bot.unresolved",
  "review.changes_requested",
  "pr.conflict",
  "wt.merged",
  "wt.created",
  "stack.parent_merged",
  "status.needs_human",
  "status.needs_testing",
  "status.ready",
  "status.verification_overdue",
  "branch.advanced",
]);
/** Legacy/alternate trigger spellings, normalized before validation. */
const TRIGGER_ALIASES: Record<string, AutomationTrigger> = {
  "rabbit.unresolved": "review_bot.unresolved",
  // The status vocabulary is hyphenated (`wt status needs-human`);
  // accept the same spelling here rather than punishing consistency.
  "status.needs-human": "status.needs_human",
  "status.needs-testing": "status.needs_testing",
};
const DEFAULT_SETTLE_SECONDS = 120;
// Merge-driven triggers are un-flappy, and the typical next step (review
// the next member, mark it ready) wants the restack done promptly — keep
// only a token cancellation window.
const MERGED_SETTLE_SECONDS = 10;
const MERGE_TRIGGERS: ReadonlySet<AutomationTrigger> = new Set([
  "wt.merged",
  "stack.parent_merged",
  // A branch tip does not move back, so there is nothing to ride out —
  // the window is only a cancellation grace period.
  "branch.advanced",
]);
// Status assertions are deliberate writes (an agent ran `wt status`),
// not flappy derived state — and their typical run is a notification,
// where a two-minute "cancellation window" is just a late ping.
const STATUS_TRIGGERS: ReadonlySet<AutomationTrigger> = new Set([
  "status.needs_human",
  "status.needs_testing",
  "status.ready",
  // Not an assertion, but the same reasoning applies twice over: this
  // condition is days old by the time it holds, so a settle window
  // measured in minutes would delay a reminder that is already late.
  "status.verification_overdue",
]);
function defaultSettleSeconds(on: AutomationTrigger): number {
  if (on === "wt.created" || STATUS_TRIGGERS.has(on)) return 0;
  return MERGE_TRIGGERS.has(on) ? MERGED_SETTLE_SECONDS : DEFAULT_SETTLE_SECONDS;
}

function parseAutomations(
  raw: unknown,
  actions: readonly ActionDef[],
  /** Branches wt actually advances — the set `branch.advanced` may watch. */
  fetched: { base: string; keepFresh: readonly string[] },
  errs: Errors,
): readonly AutomationDef[] {
  if (raw === undefined) return [];
  if (!Array.isArray(raw)) {
    errs.add("automations must be a TOML array of [[automations]] tables");
    return [];
  }
  const actionIds = new Set(actions.map((a) => a.id));
  const builtins = new Set<string>(AUTOMATION_BUILTINS);
  const out: AutomationDef[] = [];
  const seenIds = new Set<string>();
  for (let i = 0; i < raw.length; i++) {
    const entry = obj(raw[i]);
    const tag = `automations[${i}]`;
    if (!entry) {
      errs.add(`${tag} must be a table`);
      continue;
    }
    const id = errs.reqStr(entry, tag, "id");
    if (!id) continue;
    if (seenIds.has(id)) {
      errs.add(`${tag}.id "${id}" is duplicated`);
      continue;
    }
    const onRaw = entry.on;
    const on = typeof onRaw === "string" ? TRIGGER_ALIASES[onRaw] ?? onRaw : onRaw;
    if (typeof on !== "string" || !VALID_TRIGGERS.has(on as AutomationTrigger)) {
      errs.add(`${tag}.on must be one of: ${[...VALID_TRIGGERS].join(", ")}`);
      continue;
    }
    const run = errs.reqStr(entry, tag, "run");
    if (!run) continue;
    if (!actionIds.has(run) && !builtins.has(run)) {
      errs.add(
        `${tag}.run "${run}" is neither an [[actions]] id nor one of: ${AUTOMATION_BUILTINS.join(", ")}`,
      );
      continue;
    }
    // builtin:restack is the only run that targets a STACK rather than a
    // single worktree, and stack.parent_merged is the only trigger that
    // produces one — reject the mismatched pairings loudly.
    if (run === "builtin:restack" && on !== "stack.parent_merged") {
      errs.add(`${tag}: run "builtin:restack" requires on = "stack.parent_merged"`);
      continue;
    }
    if (run === "builtin:clean" && on === "stack.parent_merged") {
      errs.add(
        `${tag}: run "builtin:clean" targets one worktree; use "builtin:restack" for stack.parent_merged (it cleans merged members first)`,
      );
      continue;
    }
    // close-issue is defined by the landing: it closes the attached
    // GitHub issue once the branch merges. Every other trigger would
    // close issues for work that hasn't landed. And one rule covers
    // every worktree — a second is always a config mistake that would
    // just race the first to the same `gh issue close`.
    if (run === "builtin:close-issue") {
      if (on !== "wt.merged") {
        errs.add(`${tag}: run "builtin:close-issue" requires on = "wt.merged"`);
        continue;
      }
      if (out.some((a) => a.run === "builtin:close-issue")) {
        errs.add(`${tag}: only one builtin:close-issue rule is allowed`);
        continue;
      }
    }
    // Same shape and the same two reasons as close-issue above, and the
    // stakes are higher: the landing is what makes deleting the branch
    // safe, so any other trigger would delete the ref for work still in
    // flight — and a second rule would just race the first to a DELETE
    // that can only succeed once.
    if (run === "builtin:delete-branch") {
      if (on !== "wt.merged") {
        errs.add(`${tag}: run "builtin:delete-branch" requires on = "wt.merged"`);
        continue;
      }
      if (out.some((a) => a.run === "builtin:delete-branch")) {
        errs.add(`${tag}: only one builtin:delete-branch rule is allowed`);
        continue;
      }
    }
    const busy = errs.optEnum(
      entry,
      tag,
      "busy",
      ["queue", "skip"] as const satisfies readonly AutomationBusyPolicy[],
      "queue",
    );
    const cooldownRaw = entry.cooldown_minutes;
    if (
      cooldownRaw !== undefined &&
      !(typeof cooldownRaw === "number" && Number.isFinite(cooldownRaw) && cooldownRaw > 0)
    ) {
      errs.add(`${tag}.cooldown_minutes must be a positive number`);
      continue;
    }
    const afterDaysRaw = entry.after_days;
    if (
      afterDaysRaw !== undefined &&
      !(typeof afterDaysRaw === "number" && Number.isFinite(afterDaysRaw) && afterDaysRaw >= 0)
    ) {
      errs.add(`${tag}.after_days must be a non-negative number`);
      continue;
    }
    if (afterDaysRaw !== undefined && on !== "status.verification_overdue") {
      errs.add(
        `${tag}.after_days only applies to on = "status.verification_overdue" (got "${on}")`,
      );
      continue;
    }
    const settleRaw = entry.settle_seconds;
    if (
      settleRaw !== undefined &&
      !(typeof settleRaw === "number" && Number.isFinite(settleRaw) && settleRaw >= 0)
    ) {
      errs.add(`${tag}.settle_seconds must be a non-negative number`);
      continue;
    }
    const branchRaw = entry.branch;
    if (branchRaw !== undefined && !(typeof branchRaw === "string" && branchRaw.trim() !== "")) {
      errs.add(`${tag}.branch must be a non-empty string`);
      continue;
    }
    if (branchRaw !== undefined && on !== "branch.advanced") {
      errs.add(`${tag}.branch only applies to on = "branch.advanced" (got "${on}")`);
      continue;
    }
    if (branchRaw === undefined && on === "branch.advanced") {
      errs.add(`${tag}: on = "branch.advanced" requires branch = "<name>"`);
      continue;
    }
    const branchName = typeof branchRaw === "string" ? branchRaw.trim() : null;
    // Fail fast on a branch nothing fetches. wt advances a worktree's
    // trunk ref and the main clone's `[branch] base`; every other local
    // head moves only because `keep_fresh` names it. Watching one that
    // is never fetched is a rule that can never fire, and a rule that
    // never fires is indistinguishable from one that is working.
    if (branchName !== null && branchName !== fetched.base && !fetched.keepFresh.includes(branchName)) {
      errs.add(
        `${tag}.branch "${branchName}" is neither [branch] base nor in [branch] keep_fresh — ` +
          `nothing would advance it, so the rule could never fire`,
      );
      continue;
    }
    seenIds.add(id);
    out.push({
      id,
      on: on as AutomationTrigger,
      run,
      busy,
      cooldownMinutes: typeof cooldownRaw === "number" ? cooldownRaw : null,
      afterDays: typeof afterDaysRaw === "number" ? afterDaysRaw : VERIFY_OVERDUE_DAYS,
      settleSeconds:
        typeof settleRaw === "number" ? settleRaw : defaultSettleSeconds(on as AutomationTrigger),
      branch: branchName,
    });
  }
  return out;
}

function parseActions(raw: unknown, errs: Errors): readonly ActionDef[] {
  if (raw === undefined) return GENERIC_DEFAULTS.actions;
  if (!Array.isArray(raw)) {
    errs.add("actions must be a TOML array of [[actions]] tables");
    return GENERIC_DEFAULTS.actions;
  }
  const out: ActionDef[] = [];
  const seenIds = new Set<string>();
  for (let i = 0; i < raw.length; i++) {
    const entry = obj(raw[i]);
    const tag = `actions[${i}]`;
    if (!entry) {
      errs.add(`${tag} must be a table`);
      continue;
    }
    const id = errs.reqStr(entry, tag, "id");
    const name = errs.reqStr(entry, tag, "name");
    if (!id || !name) continue;
    if (seenIds.has(id)) {
      errs.add(`${tag}.id "${id}" is duplicated`);
      continue;
    }
    const promptVal = entry.prompt;
    const shellVal = entry.shell;
    const hasPrompt = typeof promptVal === "string" && promptVal.length > 0;
    const hasShell = typeof shellVal === "string" && shellVal.length > 0;
    // Distinguish "wrong type / empty" from "missing entirely" so the
    // error names the real problem instead of demanding a field the
    // user already tried to set.
    if (promptVal !== undefined && !hasPrompt) {
      errs.add(`${tag}.prompt must be a non-empty string`);
      continue;
    }
    if (shellVal !== undefined && !hasShell) {
      errs.add(`${tag}.shell must be a non-empty string`);
      continue;
    }
    if (hasPrompt && hasShell) {
      errs.add(`${tag} must set exactly one of "prompt" or "shell", not both`);
      continue;
    }
    if (!hasPrompt && !hasShell) {
      errs.add(`${tag} must set one of "prompt" or "shell"`);
      continue;
    }
    const affects = parseAffects(entry.affects, tag, errs);
    if (affects === "invalid") continue;
    const requires = parseRequires(entry.requires, tag, errs);
    if (requires === "invalid") continue;
    const issueStatus = entry.issue_status;
    if (issueStatus !== undefined) {
      if (!hasShell || typeof issueStatus !== "string" || !issueStatus.trim() || /[\x00-\x1f\x7f]/.test(issueStatus)) {
        errs.add(`${tag}.issue_status must be a nonempty single-line string on a shell action`);
        continue;
      }
      if (!affects?.includes("issue")) {
        errs.add(`${tag}.issue_status requires affects = ["issue"]`);
        continue;
      }
    }
    // Optional picker affordances. `key` must be a single character;
    // `group` a non-empty label. Both default to undefined (auto-derived
    // key / ungrouped) when absent.
    // Lowercase letters and digits are valid explicit picker bindings; builtins
    // reserves uppercase and punctuation for built-ins, and an
    // out-of-range key silently dies (never rendered, never dispatchable)
    // instead of erroring, so catch it here.
    const keyRaw = entry.key;
    if (keyRaw !== undefined && !(typeof keyRaw === "string" && /^[a-z0-9]$/.test(keyRaw))) {
      errs.add(`${tag}.key must be a single lowercase letter or digit (a-z, 0-9)`);
      continue;
    }
    const groupRaw = entry.group;
    if (groupRaw !== undefined && !(typeof groupRaw === "string" && groupRaw.length > 0)) {
      errs.add(`${tag}.group must be a non-empty string`);
      continue;
    }
    const externalRaw = entry.external;
    if (externalRaw !== undefined && typeof externalRaw !== "boolean") {
      errs.add(`${tag}.external must be true or false`);
      continue;
    }
    const ui: { key?: string; group?: string; external?: boolean } = {};
    if (typeof keyRaw === "string") ui.key = keyRaw;
    if (typeof groupRaw === "string") ui.group = groupRaw;
    if (externalRaw === true) ui.external = true;
    // `target` is prompt-action-only: it selects a supervised headless
    // primary-harness run (default) vs sending to the live F12 session.
    // Reject it on shell actions so a misplaced field fails loud instead
    // of silently doing nothing.
    const targetRaw = entry.target;
    if (targetRaw !== undefined) {
      if (!hasPrompt) {
        errs.add(`${tag}.target is only valid on a claude (prompt) action`);
        continue;
      }
      if (targetRaw !== "session" && targetRaw !== "headless" && targetRaw !== "manager") {
        errs.add(`${tag}.target must be "session", "manager", or "headless"`);
        continue;
      }
    }
    const target: ClaudeActionTarget =
      targetRaw === "session" || targetRaw === "manager"
        ? targetRaw
        : "headless";
    // `arg_prompt` is a single-line string ("company id") or omitted.
    // Stored as a small object so future extensions (placeholder text,
    // validation, multi-arg) don't churn the schema.
    const argPromptRaw = errs.optStrOrNull(entry, "arg_prompt");
    const argPrompt: ActionArgPrompt | null = argPromptRaw
      ? { label: argPromptRaw }
      : null;
    // `label_extract` is a regex source string. Compile-validate at
    // load time so a bad pattern fails the loader rather than silently
    // suppressing label extraction at run-time. Per-launch we recompile
    // (cheap; runs once per terminal action).
    const labelExtractRaw = errs.optStrOrNull(entry, "label_extract");
    if (labelExtractRaw !== null) {
      try {
        new RegExp(labelExtractRaw);
      } catch (err) {
        errs.add(`${tag}.label_extract: invalid regex (${(err as Error).message})`);
        continue;
      }
    }
    seenIds.add(id);
    if (hasPrompt) {
      out.push({
        kind: "claude",
        id,
        name,
        prompt: promptVal as string,
        target,
        affects: affects ?? DEFAULT_CLAUDE_AFFECTS,
        requires: requires ?? DEFAULT_REQUIRES,
        argPrompt,
        labelExtract: labelExtractRaw,
        ...ui,
      });
    } else {
      out.push({
        kind: "shell",
        id,
        name,
        shell: shellVal as string,
        ...(typeof issueStatus === "string" ? { issueStatus } : {}),
        affects: affects ?? DEFAULT_SHELL_AFFECTS,
        requires: requires ?? DEFAULT_REQUIRES,
        argPrompt,
        labelExtract: labelExtractRaw,
        ...ui,
      });
    }
  }
  return out;
}

function parseTagArray<T extends string>(
  raw: unknown,
  tag: string,
  field: "affects" | "requires",
  valid: ReadonlySet<T>,
  errs: Errors,
): readonly T[] | undefined | "invalid" {
  if (raw === undefined) return undefined;
  if (!Array.isArray(raw)) {
    errs.add(`${tag}.${field} must be an array of strings`);
    return "invalid";
  }
  const out: T[] = [];
  let bad = false;
  for (const v of raw) {
    if (typeof v !== "string") {
      errs.add(`${tag}.${field} entries must be strings`);
      bad = true;
      continue;
    }
    if (!valid.has(v as T)) {
      const allowed = [...valid].join(", ");
      errs.add(`${tag}.${field}: unknown tag "${v}" (allowed: ${allowed})`);
      bad = true;
      continue;
    }
    out.push(v as T);
  }
  if (bad) return "invalid";
  // Dedupe so `["git", "git"]` doesn't fan out to two invalidations
  // (or two precondition checks). Order is preserved.
  return [...new Set(out)];
}

function parseAffects(
  raw: unknown,
  tag: string,
  errs: Errors,
): readonly EffectTag[] | undefined | "invalid" {
  return parseTagArray(raw, tag, "affects", VALID_EFFECT_TAGS, errs);
}

function parseRequires(
  raw: unknown,
  tag: string,
  errs: Errors,
): readonly RequireTag[] | undefined | "invalid" {
  return parseTagArray(raw, tag, "requires", VALID_REQUIRE_TAGS, errs);
}

/**
 * `[paths] main_clone` and `worktree_root` as they read BEFORE the repository
 * config is chosen — the two values `canonicalRepositoryConfig` needs to tell a
 * worktree's copy of a `.wt.toml` from a repository's own.
 *
 * Deliberately tolerant and silent: this is a pre-pass, and the file it peeks
 * at is not necessarily the one wt ends up loading. Every parse error, missing
 * key and wrong type is reported once, against the file actually used, by the
 * real load below. Returning empty strings simply means "no repository config
 * can be identified", which falls back to discovery.
 */
function peekRepositoryPaths(
  userRaw: RawConfig,
  discovered: string | null,
): [mainClone: string, worktreeRoot: string] {
  let raw = userRaw;
  if (discovered && existsSync(discovered)) {
    try {
      raw = mergeConfig(userRaw, Bun.TOML.parse(readFileSync(discovered, "utf8")) as RawConfig);
    } catch {
      // Unparseable — the real load reports it.
    }
  }
  const paths = obj(raw.paths);
  const read = (key: string): string => {
    const value = paths?.[key];
    return typeof value === "string" ? expandHome(value) : "";
  };
  return [read("main_clone"), read("worktree_root")];
}

function load(): { cfg: Config; path: string } {
  const { path, present } = configPath();
  const errs = new Errors();
  const userRaw = loadRaw(path, present, errs);
  // Discovery answers "which .wt.toml is nearest my cwd"; identity has to
  // answer "which repository is this", and the two differ for every worktree
  // (each carries a copy of the file) and for every shell outside the repo
  // (which finds none). Re-point at the repository's own file BEFORE building,
  // so a `wt` run from a worktree, from the main clone, and from ~ all agree
  // on the state database, the cache root and the tmux socket.
  const discovered = repositoryConfigPath();
  const repository = canonicalRepositoryConfig(
    discovered,
    ...peekRepositoryPaths(userRaw, discovered),
  );
  let raw = userRaw;
  let sourcePath = path;
  if (repository) {
    const repositoryRaw = loadRaw(repository, existsSync(repository), errs);
    raw = mergeConfig(userRaw, repositoryRaw);
    sourcePath = repository;
    process.env[REPOSITORY_CONFIG_ENV] = repository;
  } else {
    // A stale value inherited from a parent that resolved differently would
    // otherwise short-circuit discovery in every child.
    delete process.env[REPOSITORY_CONFIG_ENV];
  }
  const cfg = build(raw, errs, repository);
  // `[paths]` naturally lives in a repository `.wt.toml`; a bare `wt`
  // outside any repo then fails with "paths.main_clone is required" and
  // no clue where the field was expected. Name both candidate homes.
  const hints: string[] = [];
  if (!repository && errs.has("paths.")) {
    hints.push(
      `no .wt.toml was found from ${process.cwd()} upward — [paths] can live in a ` +
        `repository .wt.toml (run wt inside that repo) or in ${path} as the fallback ` +
        `used everywhere else`,
    );
  }
  errs.flush(sourcePath, hints);
  return { cfg, path: sourcePath };
}

const loaded = load();

export const config: Config = Object.freeze(loaded.cfg) as Config;

/**
 * Assert SST is configured and return its config. Call from code paths
 * that only make sense with `[deploy.sst]` set (the `wt stages` command,
 * `core/sst.ts` helpers). Throws a user-readable error if not.
 */
export function requireSst(): SstConfig {
  if (!config.sst) {
    throw new Error("[deploy.sst] is not configured in config.toml");
  }
  return config.sst;
}

/**
 * Optional per-worktree dev server (`[dev_server]`). wt supervises one
 * long-lived dev-server process per worktree in a tmux session
 * (`<slug>-dev`), so it survives wt restarts, auto-restarts on crash
 * (with give-up backoff so it never thrashes), and is torn down with
 * the worktree. wt owns port allocation: each slug gets a stable port
 * from `[port_base, port_base + port_range)`, persisted in wtstate and
 * substituted for `{{port}}` in `command` (also exported as `$PORT`).
 * Strictly manual — started/stopped from the `!` picker or `wt dev`.
 */
export type DevServerConfig = {
  /**
   * Shell command run via `$SHELL -lc` inside the worktree.
   * `{{port}}` substitutes the allocated port; pin the server to it
   * (e.g. `npm run dev -- --port {{port}} --strictPort`) so the
   * recorded port and the listening port can't drift.
   */
  command: string;
  /** First port of the allocation range. */
  portBase: number;
  /** Size of the allocation range. */
  portRange: number;
  /** URL template for the row/open/yank surfaces; `{{port}}` substituted. */
  urlTemplate: string;
  /**
   * Cap on how many dev servers may run at once across the whole fleet
   * (`max_concurrent`). Null = uncapped, the historical behavior.
   *
   * Exists because a modern `dev` command is not one process. cozee's
   * brings up a twelve-container Supabase stack per worktree; twelve
   * worktrees running one each is 144 containers and an unusable
   * machine. The cap is a load governor, not a mutex — see
   * `checkDevSlot` for what "a slot" is derived from and why the
   * accounting can never drift.
   */
  maxConcurrent: number | null;
  /**
   * Teardown run after the dev server's session dies (`stop_command`).
   * Null = nothing to do, and for a plain `vite` that is correct.
   *
   * The hook exists because the resources a dev command creates are
   * routinely NOT its children: `supabase start` hands containers to
   * the docker daemon and returns, so killing the session leaves the
   * whole stack up. Measured on this machine while the cap was being
   * designed: four Supabase stacks running, only one of them with a
   * live dev session — the other three were survivors of dev servers
   * that had already been stopped. Without this, capping dev sessions
   * would govern a number with no relationship to the load.
   *
   * Same substitution and same never-fatal contract as
   * `[lifecycle] destroy_command`; see core/teardown.ts.
   */
  stopCommand: string | null;
  /**
   * Destructive teardown (`reset_command`), run by `wt dev reset`
   * between the stop and the start. Where `stop_command` releases the
   * processes and containers but KEEPS their state — which is what
   * makes retaking a slot fast, and is right nearly always — this one
   * drops it: the docker volumes, a generated cache, whatever the
   * project needs gone before the environment can be rebuilt from the
   * tree.
   *
   * A separate key rather than a flag on `stop_command` because the
   * two are wanted at different moments and the fast one is the
   * default. Its existence is also the point: the recovery was
   * previously folklore involving a raw `docker volume rm`, which
   * nobody could discover from wt.
   */
  resetCommand: string | null;
  /**
   * Project-supplied "is this environment actually usable?"
   * (`health_command`). Exit 0 = fine; non-zero = a problem, with the
   * first line of stdout used as the message.
   *
   * Exists because a listening port is not readiness, and wt cannot
   * know the difference. `wt dev start` returns as soon as the
   * supervised process is launched, so a dev command that brings up a
   * database and THEN applies migrations can fail its migration phase
   * after wt has already reported success — leaving a serviceable
   * stack on a stale schema, a green exit code, and a URL that works.
   * Only the project can ask the question that catches that.
   *
   * Run on demand only: `wt dev status`, and after the port opens on
   * `wt dev start --wait`. Never on a poll — a `docker exec psql`
   * against a live stack measured 9s on this machine, which is fine
   * once and ruinous every fifteen seconds across four worktrees.
   */
  healthCommand: string | null;
};

